// Inline spinner shown inside a loading button. Uses `currentColor`, so it
// automatically matches the button variant's text colour.
function ButtonSpinner() {
  return (
    <span
      aria-hidden="true"
      className="size-4 animate-spin rounded-full border-2 border-current border-t-transparent"
    />
  )
}

function Button({
  className,
  variant = "default",
  size = "default",
  asChild = false,
  loading = false,
  disabled,
  children,
  ...props
}: React.ComponentProps<"button"> &
  VariantProps<typeof buttonVariants> & {
    asChild?: boolean
    /** Show a spinner and disable the button while an action is in flight. */
    loading?: boolean
  }) {
  const Comp = asChild ? Slot.Root : "button"

  return (
    <Comp
      data-slot="button"
      data-variant={variant}
      data-size={size}
      data-loading={loading || undefined}
      className={cn(buttonVariants({ variant, size, className }), loading && "gap-2")}
      disabled={asChild ? disabled : disabled || loading}
      {...props}
    >
      {/* Slot (asChild) requires a single child, so pass children straight
          through; only real <button> elements get the spinner. */}
      {asChild ? (
        children
      ) : (
        <>
          {loading ? <ButtonSpinner /> : null}
          {children}
        </>
      )}
    </Comp>
  )
}

export { Button, buttonVariants }
